/**
 * ムーンクレスタ風ピクセル文字列の描画
 */
export function drawMoonCrestaText(
  ctx: CanvasRenderingContext2D,
  text: string,
  centerX: number,
  y: number,
  pixelSize = 2,
  color = '#00f0ff'
): void {
  ctx.save();
  ctx.fillStyle = color;

  const charWidth = 8 * pixelSize;
  const charSpacing = 2 * pixelSize;
  const totalWidth = text.length * charWidth + (text.length - 1) * charSpacing;
  let startX = Math.floor(centerX - totalWidth / 2);

  for (let i = 0; i < text.length; i++) {
    const char = text[i];
    const pattern = FONT_DATA[char];

    if (pattern) {
      for (let row = 0; row < pattern.length; row++) {
        const line = pattern[row];
        for (let col = 0; col < line.length; col++) {
          if (line[col] === '#') {
            ctx.fillRect(startX + col * pixelSize, y + row * pixelSize, pixelSize, pixelSize);
          }
        }
      }
    }

    startX += charWidth + charSpacing;
  }

  ctx.restore();
}
